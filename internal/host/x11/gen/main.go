// Command gen writes keysyms_gen.go from X11's keysymdef.h, XF86keysym.h and Sunkeysym.h,
// which is what keyboards use of the data libX11's XKeysymToString is built from.
//
//	go run ./internal/host/x11/gen -o internal/host/x11/keysyms_gen.go
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"slices"
	"strconv"
)

var (
	define = regexp.MustCompile(`^#define (?:XKB_KEY_|XK_|XF86XK_)?(\w+)\s+(0x[0-9a-fA-F]+)\s*(?:/\*\s*(\(?)U\+([0-9A-Fa-f]+))?`)
	vendor = regexp.MustCompile(`^#define\s+SunXK_(\w+)\s+(0x[0-9a-fA-F]+)`)
	xf86   = regexp.MustCompile(`^#define\s+XF86XK_(\w+)\s+(?:_EVDEVK\()?(0x[0-9a-fA-F]+)(\))?`)
)

const evdevBase = 0x10081000

type entry struct {
	sym  uint32
	name string
	r    rune
}

func main() {
	out := flag.String("o", "", "output file")
	inc := flag.String("I", "/usr/include/X11", "X11 include directory")

	flag.Parse()

	entries := map[uint32]*entry{}

	read(*inc+"/keysymdef.h", define, "", entries)
	read(*inc+"/XF86keysym.h", xf86, "XF86", entries)
	read(*inc+"/Sunkeysym.h", vendor, "Sun", entries)

	list := make([]*entry, 0, len(entries))
	for _, e := range entries {
		list = append(list, e)
	}

	slices.SortFunc(list, func(a, b *entry) int { return int(int64(a.sym) - int64(b.sym)) })

	var b bytes.Buffer

	fmt.Fprint(&b, "// Code generated by internal/host/x11/gen; DO NOT EDIT.\n\npackage x11\n\n")
	fmt.Fprint(&b, "// keysymEntry is a keysym, its name and the character it types, 0 for none.\n")
	fmt.Fprint(&b, "type keysymEntry struct {\n\tsym  uint32\n\tname string\n\tr    rune\n}\n\n")
	fmt.Fprint(&b, "// keysymInfo is sorted by keysym.\n")
	fmt.Fprint(&b, "var keysymInfo = [...]keysymEntry{\n")

	for _, e := range list {
		fmt.Fprintf(&b, "{%#x, %q, %#x},\n", e.sym, e.name, e.r)
	}

	fmt.Fprint(&b, "}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}

	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// read keeps the first name of a keysym, as XKeysymToString returns, so 0xff55 stays
// Prior and not Page_Up. keysymdef.h comments give the character, in parentheses when
// the match is only approximate, which XLookupString's own table includes too.
func read(path string, re *regexp.Regexp, prefix string, entries map[uint32]*entry) {
	f, err := os.Open(path)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()

	s := bufio.NewScanner(f)
	for s.Scan() {
		m := re.FindStringSubmatch(s.Text())
		if m == nil {
			continue
		}

		sym, err := strconv.ParseUint(m[2], 0, 32)
		if err != nil {
			log.Fatal(err)
		}

		// XF86keysym.h's _EVDEVK(k) is an offset into the block for Linux key codes.
		if re == xf86 && m[3] != "" {
			sym += evdevBase
		}

		e := entries[uint32(sym)]
		if e == nil {
			e = &entry{sym: uint32(sym), name: prefix + m[1]}
			entries[uint32(sym)] = e
		}

		if e.r == 0 && len(m) > 4 && m[4] != "" {
			r, err := strconv.ParseUint(m[4], 16, 32)
			if err != nil {
				log.Fatal(err)
			}

			e.r = rune(r)
		}
	}

	if err := s.Err(); err != nil {
		log.Fatal(err)
	}
}
